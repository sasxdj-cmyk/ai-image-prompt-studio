const m = (
  id: string,
  group: CategoryManifestItem['group'],
  order: number,
  name: [string, string],
  description: [string, string],
  control: CategoryManifestItem['control'],
  maxSelections: number | undefined,
  subgroups: Array<[string, [string, string], number]> = [],
  sourceTitle = 'General descriptive vocabulary (evergreen terminology)',
  exclusiveGroups: string[] = [],
): CategoryManifestItem => ({
  id,
  group,
  order,
  name: { en: name[0], it: name[1] },
  description: { en: description[0], it: description[1] },
  control,
  ...(maxSelections === undefined ? {} : { maxSelections }),
  ...(exclusiveGroups.length ? { exclusiveGroups } : {}),
  ...(subgroups.length
    ? {
        subgroups: subgroups.map(([subId, subName, subOrder]) => ({
          id: subId,
          name: { en: subName[0], it: subName[1] },
          order: subOrder,
        })),
      }
    : {}),
  source: { kind: 'terminology', title: sourceTitle },
});

