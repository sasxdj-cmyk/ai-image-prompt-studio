/**
 * Category manifest: the structural definition of every category.
 *
 * The manifest owns metadata (identity, order, control type, limits and
 * subgroups). Catalog *content* lives in `src/catalog/data/*.json`, one file
 * per group of categories, and is merged with this manifest at load time.
 *
 * Adding a category therefore means:
 *   1. adding one entry here (metadata),
 *   2. adding its entries to the matching data file (content).
 * No UI component has to change.
 */
